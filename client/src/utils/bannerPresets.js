export const DEFAULT_FALLBACK_BANNER =
  'https://images.unsplash.com/photo-1517245386807-bb43f82c33c4?auto=format&fit=crop&w=1200&q=80';

/**
 * Returns a high-definition real web banner corresponding to category or title keywords
 */
export const getCategoryBanner = (category, title = '') => {
  const normCat = category || '';
  const normTitle = (title || '').toLowerCase();

  // Keyword overrides
  if (normTitle.includes('hackathon') || normTitle.includes('code') || normTitle.includes('dev')) {
    return CATEGORY_BANNERS.Hackathon[0].url;
  }
  if (normTitle.includes('music') || normTitle.includes('cultural') || normTitle.includes('dance') || normTitle.includes('fest')) {
    return CATEGORY_BANNERS.Cultural[0].url;
  }
  if (normTitle.includes('robot') || normTitle.includes('combat') || normTitle.includes('mech')) {
    return CATEGORY_BANNERS.Competition[0].url;
  }
  if (normTitle.includes('cyber') || normTitle.includes('ctf') || normTitle.includes('hack')) {
    return CATEGORY_BANNERS.Technical[0].url;
  }
  if (normTitle.includes('cricket') || normTitle.includes('football') || normTitle.includes('sports') || normTitle.includes('futsal')) {
    return CATEGORY_BANNERS.Sports[0].url;
  }
  if (normTitle.includes('esports') || normTitle.includes('game') || normTitle.includes('gaming')) {
    return CATEGORY_BANNERS.Sports[3].url;
  }
  if (normTitle.includes('film') || normTitle.includes('cinema') || normTitle.includes('vfx')) {
    return CATEGORY_BANNERS.Arts[0].url;
  }
  if (normTitle.includes('medtech') || normTitle.includes('bio') || normTitle.includes('health')) {
    return CATEGORY_BANNERS.Innovation[0].url;
  }

  // Exact category matches
  if (CATEGORY_BANNERS[normCat] && CATEGORY_BANNERS[normCat].length > 0) {
    return CATEGORY_BANNERS[normCat][0].url;
  }

  return DEFAULT_FALLBACK_BANNER;
};

